export function buildSeed() {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const monthStart = startOfMonth(today);

  const products = PRODUCTS.map(([category, name, model, maker, price], i) => ({
    id: 'p' + String(i + 1).padStart(2, '0'),
    code: 'DM-' + String(1001 + i * 7),
    category, name, model, maker, price,
  }));

  const users = USERS.map(([name, kana, gender, birth, level, status, cmOffice, cmName], i) => {
    const certStart = toYmd(addMonths(monthStart, -(3 + (i * 5) % 14)));
    return {
      id: 'u' + String(i + 1).padStart(2, '0'),
      name, kana, gender, birth,
      zip: '999-00' + String(10 + i),
      address: `東京都デモ市${['みどり町', 'さくら台', 'かえで通り', 'ひかり丘'][i % 4]}${1 + (i % 5)}-${2 + i}-${3 + (i % 3)}`,
      phone: '03-0000-' + String(2001 + i),
      contactName: '', contactRelation: '', contactPhone: '090-0000-' + String(3001 + i),
      status,
      careLevel: level,
      certStart,
      certEnd: toYmd(addDays(addMonths(new Date(certStart), 24), -1)),
      insurerNo: '99' + String(1000 + (i % 3)).padStart(4, '0'),
      insuredNo: 'D' + String(100001 + i * 13).padStart(9, '0'),
      cmOffice, cmName,
      staff: OFFICE.staff[i % 2],
      goal: GOALS[i % GOALS.length],
      note: '',
      updatedAt: toYmd(addDays(today, -(i * 3) % 20)),
    };
  });

  const contracts = [];
  let seq = 1;
  for (const [userIdx, items] of contractPlan(monthStart, today)) {
    const user = users[userIdx];
    for (const [pNo, startAgo, endAgo, endReason] of items) {
      const p = products[pNo - 1];
      contracts.push({
        id: 'c' + String(seq++).padStart(3, '0'),
        userId: user.id,
        productId: p.id,
        price: p.price,
        start: toYmd(addDays(today, -startAgo)),
        end: endAgo == null ? '' : toYmd(addDays(today, -endAgo)),
        endReason: endAgo == null ? '' : (endReason || '終了'),
        reason: REASONS[p.category] || '',
      });
    }
  }

  return { version: 1, users, products, contracts, careOffices: CARE_OFFICES };
}
